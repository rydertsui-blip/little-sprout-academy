export type UiCopy = typeof UI_COPY | typeof UI_COPY_EN;
export type Locale = "zh" | "en";

export const SUBJECT_NAMES: Record<Subject, string> = {
  math: "数学",
  mandarin: "华文",
  english: "英语"
};

export function uiCopyFor(locale: Locale): UiCopy {
  return locale === "en" ? UI_COPY_EN : UI_COPY;
}

export function subjectLocale(subject: Subject): Locale {
  return subject === "mandarin" ? "zh" : "en";
}

export function subjectName(subject: Subject, locale: Locale): string {
  if (locale === "en") return subject === "math" ? "Mathematics" : subject === "mandarin" ? "Chinese" : "English";
  return SUBJECT_NAMES[subject];
}

export function subjectNameFor(subject: Subject): string {
  return subjectName(subject, subjectLocale(subject));
}
